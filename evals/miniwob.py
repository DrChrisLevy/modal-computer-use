"""MiniWoB++: 125 small web tasks from a standard benchmark, each scored by the page itself.

The pages come from Farama's miniwob-plusplus at a pinned commit and are served inside the Sandbox.
A task is solved when the page's own `WOB_RAW_REWARD_GLOBAL` is positive, the same test BrowserGym uses.
"""

import time
from pathlib import Path

from computers import Browser

from .browser_use import BrowserWithBrowserUse
from .tasks import Task

COMMIT = "7fd85d71a4b60325c6585396ec4f48377d049838"
ARCHIVE = f"https://github.com/Farama-Foundation/miniwob-plusplus/archive/{COMMIT}.tar.gz"
PAGES = f"/opt/MiniWoB-plusplus-{COMMIT}/miniwob/html"
SITE = "http://127.0.0.1:8888/miniwob"
ZOOM_STEPS = 7  # presses of ctrl+plus: Chromium goes 100% -> 300%, so the 160x210 task fills 480x630

NAMES = [
    line
    for line in Path(__file__).with_name("miniwob_tasks.txt").read_text().splitlines()
    if line and not line.startswith("#")
]

# Tasks that need mouse positions (dragging, drawing, pointing at a spot); a list of controls cannot express them.
NEED_POSITIONS = {
    "bisect-angle", "circle-center", "click-pie", "click-pie-nodelay", "drag-box", "drag-circle",
    "drag-cube", "drag-items", "drag-items-grid", "drag-shapes", "drag-shapes-2", "drag-single-shape",
    "drag-sort-numbers", "draw-circle", "draw-line", "find-midpoint", "highlight-text", "highlight-text-2",
    "resize-textarea", "right-angle", "use-colorwheel", "use-colorwheel-2", "use-slider", "use-slider-2",
}  # fmt: skip

# Starts one episode with a fixed seed and a time limit no agent will hit (the page's default is 10 seconds),
# and removes the overlays that would let a stray click start a second episode.
START = """(() => {
  Math.seedrandom(0);
  core.EPISODE_MAX_TIME = 3600000;
  core.startEpisodeReal();
  for (const id of ['reward-display', 'click-canvas', 'sync-task-cover']) document.getElementById(id)?.remove();
})()"""
GOAL = "(goal => typeof goal === 'string' ? goal : goal.utterance)(core.getUtterance())"
# An agent can navigate away from the task page, where these globals do not exist; that counts as not solved.
SOLVED = "typeof WOB_RAW_REWARD_GLOBAL !== 'undefined' && WOB_RAW_REWARD_GLOBAL > 0"
DONE = "typeof WOB_DONE_GLOBAL !== 'undefined' && WOB_DONE_GLOBAL === true"

fetch = f"import tarfile, urllib.request; tarfile.open(fileobj=urllib.request.urlopen('{ARCHIVE}'), mode='r|gz')"


class MiniwobBrowser(BrowserWithBrowserUse):
    """A Browser with the MiniWoB++ pages on disk. It also has Browser Use, so every agent can run on it."""

    image = BrowserWithBrowserUse.image.run_commands(f"python -c \"{fetch}.extractall('/opt')\"")

    def actions(self, view: str) -> dict[str, str]:
        """A task lives on one page, and loading it again starts a different episode, so `goto` is not offered."""
        return {name: line for name, line in super().actions(view).items() if name != "goto"}


def miniwob_task(name: str) -> Task:
    def setup(browser: Browser) -> None:
        serve = f"cd {PAGES} && (nohup python -m http.server 8888 --bind 127.0.0.1 >/dev/null 2>&1 &)"
        wait = "until (echo >/dev/tcp/127.0.0.1/8888) 2>/dev/null; do sleep 0.1; done"
        browser.run("bash", "-c", f"{serve} && {wait}")
        browser.goto(f"{SITE}/{name}.html")
        browser.eval(START)
        while not browser.eval("WOB_TASK_READY"):
            time.sleep(0.2)
        browser.key("ctrl+0")  # zoom is remembered per site, so start from 100%
        for _ in range(ZOOM_STEPS):
            browser.key("ctrl+plus")

    return Task(
        name,
        MiniwobBrowser,
        prompt="",
        setup=setup,
        check=lambda browser: browser.eval(SOLVED),
        instruction=lambda browser: browser.eval(GOAL),  # each episode's instruction is generated by the page
        finished=lambda browser: browser.eval(DONE),
        max_steps=15,
    )


TASKS = [miniwob_task(name) for name in NAMES]
